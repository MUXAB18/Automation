#!/usr/bin/env node
// Creates .env.docker with generated secrets (once). Never prints a secret.
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const target = new URL("../.env.docker", import.meta.url);
if (existsSync(target)) {
  console.log(".env.docker already exists: left unchanged.");
  process.exit(0);
}

// Reuse the admin login from the local .env (if present) so signing in works the same everywhere.
const local = new Map();
try {
  for (const line of readFileSync(new URL("../.env", import.meta.url), "utf8").split("\n")) {
    const m = /^([A-Z0-9_]+)=(.*)$/.exec(line.trim());
    if (m) local.set(m[1], m[2].replace(/^['"]|['"]$/g, ""));
  }
} catch {
  // no local .env
}

const secret = (bytes) => randomBytes(bytes).toString("hex");
const lines = [
  "# Generated by `npm run docker:init`. Keep this file private (it is git-ignored).",
  `POSTGRES_PASSWORD=${secret(18)}`,
  `BETTER_AUTH_SECRET=${secret(32)}`,
  `ENCRYPTION_KEY=${randomBytes(32).toString("base64")}`,
  `ML_SERVICE_TOKEN=${secret(24)}`,
  "APP_URL=http://localhost:3000",
  `SEED_ADMIN_EMAIL=${local.get("SEED_ADMIN_EMAIL") ?? "admin@example.com"}`,
  `SEED_ADMIN_PASSWORD=${local.get("SEED_ADMIN_PASSWORD") ?? secret(12)}`,
  `SEED_ADMIN_NAME=${local.get("SEED_ADMIN_NAME") ?? "Admin"}`,
  local.get("SEED_DEV_USER_PASSWORD") ? `SEED_DEV_USER_PASSWORD=${local.get("SEED_DEV_USER_PASSWORD")}` : "# SEED_DEV_USER_PASSWORD=   (development only: one sample user per role)",
  "",
  "# Optional integrations (leave empty to use the development mocks)",
  "# GHL_CLIENT_ID=",
  "# GHL_CLIENT_SECRET=",
  "# GHL_REDIRECT_URI=http://localhost:3000/api/integrations/gohighlevel/callback",
  "# GOOGLE_CLIENT_ID=",
  "# GOOGLE_CLIENT_SECRET=",
  "# GOOGLE_REDIRECT_URI=http://localhost:3000/api/integrations/google/callback",
  "",
];
writeFileSync(target, lines.join("\n"), { mode: 0o600 });
console.log(
  local.has("SEED_ADMIN_PASSWORD")
    ? "Created .env.docker. The admin login is the one from your .env."
    : "Created .env.docker. The generated admin password is SEED_ADMIN_PASSWORD in that file.",
);
